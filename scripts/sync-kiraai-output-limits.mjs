/**
 * sync-kiraai-output-limits.mjs
 * Pulls kiraai's public model catalog and regenerates
 * packages/translator/concerns/kiraaiOutputLimits.js (chat model id → output_limit).
 * Usage: node scripts/sync-kiraai-output-limits.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CATALOG_URL = "https://kiraai.vn/api/v1/models";
const OUT = fileURLToPath(new URL("../packages/translator/concerns/kiraaiOutputLimits.js", import.meta.url));
// The catalog has junk rows (output_limit 0 / 65); a cap that low would cripple the model.
const MIN_PLAUSIBLE_LIMIT = 1024;

const res = await fetch(CATALOG_URL, { signal: AbortSignal.timeout(20000) });
if (!res.ok) throw new Error(`GET ${CATALOG_URL} → ${res.status}`);
const { data } = await res.json();
if (!Array.isArray(data)) throw new Error("Unexpected catalog shape: no data[]");

const limits = {};
const skipped = [];
for (const m of data) {
  if (m?.type !== "chat" || typeof m.id !== "string") continue;
  const limit = Number(m.output_limit);
  if ((m.output_limit_unit ?? "tokens") !== "tokens" || !Number.isInteger(limit) || limit < MIN_PLAUSIBLE_LIMIT) {
    skipped.push(`${m.id}=${m.output_limit}`);
    continue;
  }
  limits[m.id] = limit;
}

const body = Object.keys(limits).sort()
  .map((id) => `  ${JSON.stringify(id)}: ${limits[id]},`)
  .join("\n");

writeFileSync(OUT, `// AUTO-GENERATED by scripts/sync-kiraai-output-limits.mjs from ${CATALOG_URL}
// on ${new Date().toISOString().slice(0, 10)} — do not hand-edit; re-run the script.
// Catalog values can be wrong: put verified upstream caps in KIRAAI_OUTPUT_OVERRIDES
// (packages/translator/concerns/paramSupport.js), which wins over this table.
export const KIRAAI_OUTPUT_LIMITS = {
${body}
};
`);

console.log(`Wrote ${Object.keys(limits).length} kiraai chat model limits → ${OUT}`);
if (skipped.length) console.log(`Skipped (implausible limit): ${skipped.join(", ")}`);
